#!/usr/bin/env python3
"""
Fill the Round 2 placeholders in one shot.

Usage:
    python finalize_round2.py <repo-url> <deploy-url>

    e.g. python finalize_round2.py \
        https://github.com/pal-123456789/flowforge-r2 \
        https://flowforge-r2.vercel.app

What it does:
  1. replaces __REPO_URL__ / __DEPLOY_URL__ in every Markdown file
  2. writes .env.local with the same values (for the product's Source button
     and the deployment link)
  3. regenerates FlowForge_Round2.pptx with the real URLs baked in
  4. prints a summary and any placeholder it could not resolve

Safe to re-run. It is idempotent.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MD_FILES = [
    "README.md", "API.md", "ARCHITECTURE.md", "FEATURES.md",
    "CHANGELOG.md", "DISCLOSURE.md", "DEMO_SCRIPT.md", "Q_AND_A_BANK.md",
]


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    repo = sys.argv[1].strip().rstrip("/")
    deploy = sys.argv[2].strip().rstrip("/")

    for name, value in (("__REPO_URL__", repo), ("__DEPLOY_URL__", deploy)):
        if not value:
            print(f"ERROR: {name} resolved to an empty value")
            return 2
    if not repo.startswith("http") or not deploy.startswith("http"):
        print("ERROR: both URLs must start with http:// or https://")
        return 2

    changed = []
    for fname in MD_FILES:
        path = os.path.join(HERE, fname)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        new = text.replace("__REPO_URL__", repo).replace("__DEPLOY_URL__", deploy)
        if new != text:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(new)
            changed.append(fname)

    env_local = os.path.join(HERE, ".env.local")
    with open(env_local, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "# Generated by finalize_round2.py - git-ignored.\n"
            f"NEXT_PUBLIC_REPO_URL={repo}\n"
            f"NEXT_PUBLIC_DEPLOY_URL={deploy}\n"
        )

    # regenerate the deck with the real URLs
    env = dict(os.environ, FF_REPO_URL=repo, FF_DEPLOY_URL=deploy)
    py = sys.executable
    try:
        subprocess.run([py, os.path.join(HERE, "make_ppt_round2.py")],
                       cwd=HERE, env=env, check=True)
        deck = "FlowForge_Round2.pptx (regenerated)"
    except Exception as exc:  # noqa: BLE001
        deck = f"NOT regenerated: {exc}"

    # report anything still unresolved
    leftover = []
    for fname in MD_FILES:
        path = os.path.join(HERE, fname)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            if "__REPO_URL__" in f.read() or "__DEPLOY_URL__" in f.read():
                leftover.append(fname)

    print()
    print(f"repo    : {repo}")
    print(f"deploy  : {deploy}")
    print(f"docs    : {', '.join(changed) if changed else '(no changes needed)'}")
    print(f"env     : .env.local written")
    print(f"deck    : {deck}")
    if leftover:
        print(f"WARNING unresolved placeholders still in: {', '.join(leftover)}")
        return 1
    print("OK - no unresolved placeholders in any Markdown file.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
